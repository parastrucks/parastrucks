// Phase 10 — writes SQL that loads N DUMMY vehicles into STAGING, for building and timing the grid.
//
//   node scripts/phase10/gen-demo-rows.mjs 2050 > <scratch>/demo.sql
//   npx supabase@2.109.1 db query --linked --workdir <scratch>/sb -f <scratch>/demo.sql
//
// Every value is invented (no workbook is read). Every chassis starts "DEMO-" and every row carries
// source_file = 'DEMO seed', so they can be found (and, with the owner's approval, removed).
// The rows are inserted with recompute = true, so the database works out every formula itself.
// Seeded random numbers: the same N gives the same book.

const N = Number(process.argv[2] || 2050)
// mulberry32. ⚠️ The first version used `seed * 1103515245 % 2**31` in plain JS numbers: the product
// passes 2**53 and loses precision, so the sequence cycled and the 2026-10-22 staging load has runs
// of identical rows (same model, V-part, customer, CTC on different chassis). Harmless, but it looked
// like a grid bug during the sort check.
let seed = 20261022
const rnd = () => {
  seed = (seed + 0x6D2B79F5) | 0
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed)
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296
}
const pick = (a) => a[Math.floor(rnd() * a.length)]
const int = (lo, hi) => lo + Math.floor(rnd() * (hi - lo + 1))
const iso = (d) => d.toISOString().slice(0, 10)
const addDays = (s, n) => iso(new Date(Date.parse(s) + n * 86400000))

const MODELS = [['BOSS 1115 HB', 'ICV TRUCK'], ['ECOMET 1615 HE', 'ICV TRUCK'], ['2820 TIPPER', 'TIPPER'],
  ['3520 HAULAGE', 'HAULAGE'], ['4825 MAV', 'MAV'], ['OYSTER WIDE', 'BUS'], ['VIKING 51S', 'BUS'],
  ['DOST+ XL', 'LCV'], ['PARTNER 6T', 'LCV'], ['1920 TRACTOR', 'TRACTOR']]
const DSES = ['DEMO RAVI', 'DEMO ANITA', 'DEMO KIRAN', 'DEMO SURESH', 'DEMO MEENA', 'DEMO FAROOQ', 'DEMO JOSE']
const BANKS = ['HDFC BANK', 'ICICI BANK', 'SBI', 'AXIS BANK', 'IndusInd', 'CASH']
const PLACES = ['AHMEDABAD', 'SURAT', 'VADODARA', 'RAJKOT', 'BHAVNAGAR', 'MEHSANA']
const YEARS = ['R', 'S', 'S', 'S', 'T'] // VIN position 10: 2024, 2025, 2026

const q = (v) => v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`
const lines = []
for (let i = 1; i <= N; i++) {
  const [model, segment] = pick(MODELS)
  const chassis = `DEMO-${'MB1A'}${pick(YEARS)}${String(i).padStart(7, '0')}`
  const gpDate = iso(new Date(Date.UTC(2025, 3, 1) + int(0, 360) * 86400000))
  const ctc = int(15, 48) * 100000 + int(0, 99) * 1000
  const ctd = Math.round(ctc * (0.92 + rnd() * 0.04) / 100) * 100
  const sold = rnd() < 0.8
  const invoice = sold ? addDays(gpDate, int(2, 90)) : null
  const paid = rnd() < 0.85 ? addDays(gpDate, int(0, 30)) : null
  const tally = sold ? Math.round(ctc * (1.02 + rnd() * 0.05) / 100) * 100 : null
  const mrp = Math.round(ctc * 1.12 / 1000) * 1000
  const finance = sold && rnd() < 0.7
  const delivered = sold && rnd() < 0.9
  const row = {
    chassis_no: chassis, engine_no: `DEMOE${String(i).padStart(6, '0')}`, model, segment,
    vpart_no: `DEMOV${int(1000, 9999)}`, customer_name: sold ? `DEMO CUSTOMER ${int(1, 900)}` : null,
    purchase_source: rnd() < 0.95 ? 'al' : 'other_dealer', oem_gatepass_no: `DEMOGP${String(100000 + i)}`,
    oem_gatepass_date: gpDate, ctc, ctd, amc_to_al: rnd() < 0.3 ? int(5, 40) * 1000 : null,
    dsa: rnd() < 0.2 ? int(2, 15) * 1000 : null, al_payment_status: paid ? pick(['Cash Invoiced', 'IBND']) : null,
    al_payment_date: paid, ptb_invoice_date: invoice,
    supplier_invoice_amount: rnd() < 0.5 ? ctd + int(-5, 5) * 1000 : null,
    dse: sold ? pick(DSES) : null, delivery_location: sold ? pick(PLACES) : null,
    finance_bank: sold ? pick(BANKS) : null, mrp, tally_bill: tally,
    margin_money: sold ? Math.round(tally * (finance ? 0.15 : 1) / 1000) * 1000 : null,
    finance_recd: finance ? Math.round(tally * 0.85 / 1000) * 1000 : null,
    finance_paymt_recd_date: finance && rnd() < 0.8 ? addDays(invoice, int(3, 40)) : null,
    insurance: sold ? int(30, 90) * 1000 : null, cretem: sold ? pick([5600, 6800, 7000, 7400]) : null,
    road_tax_pct: segment === 'BUS' && rnd() < 0.4 ? 0 : 6,
    delivery_status: !sold ? 'Stock' : delivered ? 'DELIVERED' : 'PENDING',
    dsm: sold ? pick(['DEMO DSM NORTH', 'DEMO DSM SOUTH']) : null,
    date_of_retail: invoice, date_of_delivery: delivered ? addDays(invoice, int(0, 10)) : null,
    retention_al_claim: sold && rnd() < 0.6 ? Math.round((ctc - ctd) / 500) * 500 : null,
    source_file: 'DEMO seed', source_row: i,
  }
  const cols = Object.keys(row)
  lines.push(`(${cols.map((k) => q(row[k])).join(', ')})`)
  if (i === 1) lines.colList = cols.join(', ')
}

console.log(`-- ${N} DUMMY vehicles for STAGING (generated by scripts/phase10/gen-demo-rows.mjs)
begin;
select set_config('tracker.source', 'import', true);
insert into public.vehicle_units (${lines.colList}) values
${lines.join(',\n')};
commit;`)
